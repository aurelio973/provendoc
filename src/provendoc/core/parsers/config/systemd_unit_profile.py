# -*- coding: utf-8 -*-
"""systemd unit summary rendering.

Markdown/JSON/Graph auxiliary views that never replace the
contract: the source of truth stays the ``config_entries`` contract
plus the ``systemd_profile`` metadata.  The Markdown output states
explicitly that it does not preserve repeated directives, reset
semantics, drop-in provenance, specifiers, argv structure,
dependency edges, or enabled/active state.
"""

_PROFILE_VERSION = "systemd_unit_profile_p1"

# Value clipping for summary columns (auxiliary views are lossy;
# full text lives in contract raw_value)
_VALUE_CLIP = 120

_AUXILIARY_NOTE = (
    "<!-- auxiliary view generated by provendoc; not the original "
    "unit source; does not replace: repeated directives, reset "
    "semantics, drop-in provenance, specifiers, argv structure, "
    "dependency edges, enablement state -->"
)


def _clip(text: str) -> str:
    if text is None:
        return ""
    text = str(text)
    if len(text) > _VALUE_CLIP:
        return text[:_VALUE_CLIP] + "…"
    return text


def _entry_value(entry: dict) -> str:
    """Summary value column (decoded → logical → raw preference chain;
    surrounding quotes stripped)."""
    v = entry.get("decoded_value")
    if v is None:
        v = entry.get("logical_value")
    if v is None:
        v = entry.get("raw_value")
    if v is None:
        return ""
    v = str(v).strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in ("'", '"'):
        v = v[1:-1]
    return v


def _grouped_entries(contract: dict) -> dict[str, list[dict]]:
    """Group entries by section (order preserved; entries without a
    section are skipped)."""
    groups: dict[str, list[dict]] = {}
    for e in contract.get("entries", []):
        sec = e.get("section")
        if not sec:
            continue
        groups.setdefault(sec, []).append(e)
    return groups


def render_systemd_summary(profile: dict, contract: dict) -> str:
    """Markdown summary for a service/timer unit."""
    lines: list[str] = []
    lines.append(f"# {profile.get('unit_name') or 'unit'}")
    lines.append("")
    lines.append(_AUXILIARY_NOTE)
    lines.append("")
    for sec, entries in _grouped_entries(contract).items():
        lines.append(f"## [{sec}]")
        lines.append("")
        lines.append("| Directive | Value |")
        lines.append("|---|---|")
        for e in entries:
            key = e.get("key") or (e.get("path") or [None])[-1]
            lines.append(f"| `{key}` | {_clip(_entry_value(e))} |")
        lines.append("")
    findings = profile.get("security_directive_findings") or []
    env_files = profile.get("environment_files") or []
    if findings or env_files:
        lines.append("## Security Findings")
        lines.append("")
        for f in findings:
            if f.get("key") == "EnvironmentFile":
                lines.append("- `EnvironmentFile` not read.")
            else:
                lines.append(f"- `{f.get('key')}` detected; execution was not attempted.")
        lines.append("")
    if not _grouped_entries(contract):
        # Empty-contract fallback: still emit a usable skeleton
        lines.append("_(no directives recovered)_")
        lines.append("")
    return "\n".join(lines)


def render_systemd_json(profile: dict, contract: dict) -> dict:
    """Structured JSON view (auxiliary projection — not a contract
    replacement)."""
    sections: dict[str, list[dict]] = {}
    timer_schedules: list[dict] = []
    for e in contract.get("entries", []):
        sec = e.get("section")
        if not sec:
            continue
        item = {
            "key": e.get("key") or (e.get("path") or [None])[-1],
            "value": _entry_value(e),
            "cardinality": e.get("cardinality"),
        }
        if e.get("security_class"):
            item["security_class"] = e["security_class"]
        sections.setdefault(sec, []).append(item)
        if e.get("timer_schedule"):
            timer_schedules.append(e["timer_schedule"])
    return {
        "profile_version": _PROFILE_VERSION,
        "unit_name": profile.get("unit_name"),
        "unit_type": profile.get("unit_type"),
        "template_instance": profile.get("template_instance"),
        "unit_context": profile.get("unit_context"),
        "unit_enablement": profile.get("unit_enablement"),
        "sections": sections,
        "unit_relations": profile.get("unit_relations") or [],
        "install_targets": profile.get("install_targets") or {},
        "timer_schedules": timer_schedules,
        "environment_files": profile.get("environment_files") or [],
        "credential_references": profile.get("credential_references") or [],
        "security_findings": profile.get("security_directive_findings") or [],
        "loss_codes": profile.get("loss_codes") or [],
    }


def render_systemd_graph(profile: dict) -> dict:
    """Dependency-graph projection (nodes/edges; this view only
    projects the edge list)."""
    relations = profile.get("unit_relations") or []
    nodes: list[dict] = [{"id": profile.get("unit_name") or "unit", "kind": "unit"}]
    seen: set[str] = set()
    for r in relations:
        target = r.get("target")
        if target and target not in seen:
            seen.add(target)
            nodes.append({"id": target, "kind": "unit_candidate"})
    return {"nodes": nodes, "edges": relations}


