# ==================================


def _assembly_sources_table(unit: dict) -> list[str]:
    """Unit sources table rows (file/role/shadowed — records tier
    winners and shadowed drop-ins)."""
    lines = [
        "### Sources",
        "",
        "| File | Role | Shadowed |",
        "|---|---|---|",
    ]
    for us in unit.get("unit_sources") or []:
        name = (us.get("file") or "").replace("\\", "/").split("/")[-1]
        lines.append(
            f"| `{_clip(name)}` | {us.get('role') or 'base'} | "
            f"{'yes' if us.get('shadowed') else 'no'} |"
        )
    lines.append("")
    return lines


def _assembly_candidate_tables(unit: dict) -> list[str]:
    """Per-section merged-candidate tables.

    Slot keys look like ``Section/Key``; effective_values are all kept
    and shown clipped (the list carries the merged result of
    multi-value appends/resets; raw values stay in the contract).
    """
    lines: list[str] = []
    candidate = unit.get("merged_candidate") or {}
    sections: dict[str, list[tuple[str, dict]]] = {}
    for slot_key in sorted(candidate):
        sec, _, key = slot_key.partition("/")
        sections.setdefault(sec, []).append((key, candidate[slot_key]))
    if not sections:
        return lines
    lines.append("### Merged Candidate")
    lines.append("")
    for sec, items in sections.items():
        lines.append(f"#### [{sec}]")
        lines.append("")
        lines.append("| Directive | Value |")
        lines.append("|---|---|")
        for key, slot in items:
            values = slot.get("effective_values") or []
            shown = ", ".join(_clip(v) for v in values) if values else "_(reset)_"
            lines.append(f"| `{key}` | {shown} |")
        lines.append("")
    return lines


def render_assembly_summary(assembly: dict) -> str:
    """Assembly-level Markdown summary (auxiliary view — not a
    contract replacement).

    Input is the ``assemble_units`` output (``{units, dependency_graph}``):
    one section per unit (Sources table / Merged Candidate tables /
    Merge Conflicts / Security Findings), then a Dependency Graph
    overview (nodes + cycles; cycles appear only when non-empty).
    Like the per-unit views, the Markdown explicitly does not
    replace the contract's preserved facts.
    """
    lines: list[str] = []
    lines.append("# systemd unit assembly")
    lines.append("")
    lines.append(_AUXILIARY_NOTE)
    lines.append("")
    units = assembly.get("units") or []
    graph = assembly.get("dependency_graph") or {}
    edges = graph.get("edges") or []
    if not units:
        lines.append("_(no units assembled)_")
        lines.append("")
        return "\n".join(lines)
    for unit in units:
        lines.append(f"## {unit.get('unit_name') or 'unit'}")
        lines.append("")
        lines.extend(_assembly_sources_table(unit))
        lines.extend(_assembly_candidate_tables(unit))
        conflicts = unit.get("merge_conflicts") or []
        if conflicts:
            lines.append("### Merge Conflicts")
            lines.append("")
            for c in conflicts:
                lines.append(
                    f"- `{c.get('code')}`: {_clip(c.get('detail') or '')}"
                )
            lines.append("")
        env_files = unit.get("environment_files") or []
        findings = unit.get("security_findings") or []
        if findings or env_files:
            lines.append("### Security Findings")
            lines.append("")
            for f in findings:
                if f.get("key") == "EnvironmentFile":
                    lines.append("- `EnvironmentFile` not read.")
                else:
                    lines.append(
                        f"- `{f.get('key')}` detected; "
                        "execution was not attempted."
                    )
            lines.append("")
        unit_edges = [e for e in edges if e.get("source") == unit.get("unit_name")]
        if unit_edges:
            lines.append("### Dependency Edges")
            lines.append("")
            for e in unit_edges:
                lines.append(
                    f"- `{e.get('source')}` --{e.get('edge_type')}--> "
                    f"`{e.get('target')}` ({e.get('resolution_status')})"
                )
            lines.append("")
    lines.append("## Dependency Graph")
    lines.append("")
    nodes = graph.get("nodes") or []
    lines.append(f"- nodes: {', '.join(f'`{n}`' for n in nodes) if nodes else '_(none)_'}")
    cycles = graph.get("cycles") or []
    if cycles:
        for path in cycles:
            lines.append(
                f"- cycle: {' -> '.join(f'`{n}`' for n in path)}"
                f" -> `{path[0]}`"
            )
    lines.append("")
    return "\n".join(lines)
